#!/usr/bin/env python3
"""Rigid SPC/E water NPT with LAMMPS KOKKOS: input generator.

Converts the shared GROMACS state (.gro, nm, nm/ps) into a LAMMPS data file in
`real` units (Angstrom, fs, kcal/mol) and writes the input script. The model matches
the other engines: SPC/E, SHAKE (bonds and angle), LJ with potential shift, no tail
correction, r_c = 10 A, PPPM with explicit parameters, CSVR (fix temp/csvr/kk, our
KOKKOS port) on top of an MTK barostat without its own thermostat (fix nph/kk, iso).
Output only after the last step (write_dump of positions and velocities; the volume
average of fix ave/time is written once, at the end).
Usage: lammps_npt.py --gro state.gro --dir RUNDIR --pppm gewald,nx,ny,nz,order [--steps 10000]
"""
import argparse, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

QO, QH = -0.8476, 0.4238
SIG_A, EPS_KCAL = 3.16557, 0.650629 / 4.184
MO, MH = 15.9994, 1.008
THETA = 2 * math.degrees(math.asin(0.08165 / 0.1))   # from O-H 0.1 nm, H-H 0.16330 nm


def read_gro(path):
    with open(path) as f:
        f.readline(); n = int(f.readline())
        lines = [f.readline() for _ in range(n)]
        box = [float(b) for b in f.readline().split()[:3]]
    tail = lines[0][20:]; d1 = tail.index("."); w = tail.index(".", d1 + 1) - d1
    xs, vs = [], []
    for line in lines:
        t = line[20:]
        xs.append([float(t[k * w:(k + 1) * w]) for k in range(3)])
        r = t[3 * w:]
        vs.append([float(r[k * (w + 1):(k + 1) * (w + 1)]) for k in range(3)] if r.strip() else [0.0, 0.0, 0.0])
    return xs, vs, box


def write_data(path, xs, vs, box):
    n = len(xs); nw = n // 3
    L = [10 * b for b in box]
    with open(path, "w") as f:
        f.write("SPC/E water (real units)\n\n%d atoms\n%d bonds\n%d angles\n\n2 atom types\n1 bond types\n1 angle types\n\n" % (n, 2 * nw, nw))
        f.write("0 %.8f xlo xhi\n0 %.8f ylo yhi\n0 %.8f zlo zhi\n\nMasses\n\n1 %.4f\n2 %.4f\n\nAtoms # full\n\n" % (*L, MO, MH))
        for i, x in enumerate(xs):
            mol = i // 3 + 1; t = 1 if i % 3 == 0 else 2; q = QO if t == 1 else QH
            f.write("%d %d %d %.4f %.7f %.7f %.7f\n" % (i + 1, mol, t, q, 10 * x[0], 10 * x[1], 10 * x[2]))
        f.write("\nVelocities\n\n")
        for i, v in enumerate(vs):   # nm/ps -> A/fs
            f.write("%d %.9f %.9f %.9f\n" % (i + 1, 0.01 * v[0], 0.01 * v[1], 0.01 * v[2]))
        f.write("\nBonds\n\n")
        for w in range(nw):
            o = 3 * w + 1
            f.write("%d 1 %d %d\n%d 1 %d %d\n" % (2 * w + 1, o, o + 1, 2 * w + 2, o, o + 2))
        f.write("\nAngles\n\n")
        for w in range(nw):
            o = 3 * w + 1
            f.write("%d 1 %d %d %d\n" % (w + 1, o + 1, o, o + 2))


def write_input(path, data, pppm, steps, seed, nevery_avg, skin=2.0, every=1):
    rundir = os.path.dirname(os.path.abspath(path))   # absolute paths: LAMMPS may run elsewhere
    pair = "lj/cut/coul/long 10.0"
    if pppm[0] == "accuracy":     # LAMMPS chooses g_ewald and the grid from the accuracy (order 5)
        kspace = "kspace_style pppm %g\nkspace_modify order 5" % pppm[1]
    elif pppm[0] == "esp":        # LAMMPS-ESP (CPU fork): prolate split and window from the accuracy
        kspace = "kspace_style esp %g" % pppm[1]
        pair = "lj/cut/coul/esp 10.0"
    else:
        g, nx, ny, nz, order = pppm
        kspace = "kspace_style pppm 1.0e-5\nkspace_modify gewald %g mesh %d %d %d order %d" % (g, nx, ny, nz, order)
    with open(path, "w") as f:
        f.write(f"""# Rigid SPC/E water NPT, LAMMPS KOKKOS (generated by lammps_npt.py)
units real
atom_style full
boundary p p p
read_data {os.path.join(rundir, data)}
pair_style {pair}
pair_coeff 1 1 {EPS_KCAL:.8f} {SIG_A}
pair_coeff 2 2 0.0 1.0
pair_coeff 1 2 0.0 1.0
pair_modify shift yes tail no
{kspace}
bond_style harmonic
bond_coeff 1 1000.0 1.0
angle_style harmonic
angle_coeff 1 100.0 {THETA:.6f}
special_bonds lj/coul 0.0 0.0 0.0
neighbor {skin} bin
neigh_modify every {every} delay 0 check yes
timestep 2.0
fix rigid all shake 1.0e-6 100 0 b 1 a 1
fix baro all nph iso 1.0 1.0 5000.0
fix thermo_csvr all temp/csvr 298.0 298.0 100.0 {seed}
variable vol equal vol
# volume averaged in memory: one sample every {nevery_avg} steps, written once at the last step
fix vavg all ave/time {nevery_avg} {steps // nevery_avg} {steps} v_vol file {os.path.join(rundir, "volume_average.txt")}
thermo {steps}
thermo_style custom step temp press vol density pe
timer sync
run {steps}
write_dump all custom {os.path.join(rundir, "final.dump")} id mol type x y z vx vy vz modify sort id format float %.7f
""")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--gro", required=True); p.add_argument("--dir", required=True)
    p.add_argument("--pppm", help="gewald (1/A),nx,ny,nz,order")
    p.add_argument("--pppm-accuracy", type=float, help="PPPM accuracy (instead of --pppm)")
    p.add_argument("--esp-accuracy", type=float, help="LAMMPS-ESP accuracy (CPU fork; instead of --pppm)")
    p.add_argument("--steps", type=int, default=10000); p.add_argument("--seed", type=int, default=29)
    p.add_argument("--avg-every", type=int, default=100)
    p.add_argument("--skin", type=float, default=2.0, help="neighbor skin (A)")
    p.add_argument("--neigh-every", type=int, default=1, help="neighbor check interval (steps)")
    a = p.parse_args()
    os.makedirs(a.dir, exist_ok=True)
    xs, vs, box = read_gro(a.gro)
    write_data(os.path.join(a.dir, "water.data"), xs, vs, box)
    if a.esp_accuracy is not None:
        pppm = ("esp", a.esp_accuracy)
    elif a.pppm_accuracy is not None:
        pppm = ("accuracy", a.pppm_accuracy)
    else:
        t = a.pppm.split(","); pppm = (float(t[0]), int(t[1]), int(t[2]), int(t[3]), int(t[4]))
    write_input(os.path.join(a.dir, "in.water"), "water.data", pppm, a.steps, a.seed, min(a.avg_every, a.steps),
                skin=a.skin, every=a.neigh_every)
    print("wrote", a.dir)


if __name__ == "__main__":
    main()
