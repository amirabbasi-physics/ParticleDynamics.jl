module GoldenFixtures
using Test, SHA
using Pkg.Artifacts: artifact_path, download_artifact, verify_artifact
export golden_directory, golden_available, check_golden_fixtures, announce_test_run,
       prepare_golden_fixtures, @golden_testset

const REFERENCE_SHA256 = "2bccb54bd211ca064d7c282b2fecedc7d75571cc9b5c71989bbbb8dab744055d"
const REFERENCE_TREE = Base.SHA1("1628f80a329c43dc059957296ac65c6d08f48aa5")
# Set only after this exact archive has been published. Mirrors must have the same hash.
const REFERENCE_URL = ""

const DATASETS = (
    deterministic = ("PD_GOLDEN_DIR", "v1-20261009T122031"),
    engine = ("PD_ENGINE_GOLDEN_DIR", "v3-engine-tests"),
    equilibrium_2d = ("PD_GOLDEN_EQ2D", "v2-eq-20261009T180331"),
    equilibrium_3d = ("PD_GOLDEN_EQ3D", "v2-eq3d-liquid-20261009T190013"),
)
const VERIFIED = Set{String}()
const WARNED = Set{String}()

"""Print the measured full-suite runtime estimate before loading CUDA or running tests."""
function announce_test_run(io::IO=stdout)
    println(io, "ParticleDynamics test suite")
    println(io, "Estimated full-suite time: 30–45 minutes on an NVIDIA RTX 3090 (Julia 1.12).")
    println(io, "First-time compilation or slower hardware can take longer; this is not a deadline.")
    missing = [kind for kind in keys(DATASETS) if !isdir(golden_directory(kind))]
    if isempty(missing)
        println(io, "All four reference directories are present; their checksums will be verified.")
    else
        println(io, "Missing reference datasets: ", join(string.(missing), ", "))
        println(io, "Optional references: 24.8 MB download, 68.1 MB unpacked, cached outside the repository.")
        println(io, "Download time is additional and depends on your connection.")
        println(io, "Skipping references gives partial validation; no separate runtime estimate is calibrated.")
        get(ENV, "PD_REQUIRE_GOLDEN", "0") == "1" &&
            println(io, "Strict mode: all reference datasets are required; skipping missing data stops the run.")
    end
    println(io, "Historical references are not regenerated by the implementation under test.")
    flush(io)
    return nothing
end

"""External fixture directory, with a per-dataset override or a shared root."""
function golden_directory(kind::Symbol)
    variable, subdir = getproperty(DATASETS, kind)
    # Preserve explicitly configured paths, including missing ones. Never silently replace them.
    local_root = joinpath(@__DIR__, "golden")
    default_root = ispath(joinpath(local_root, subdir)) ? local_root :
        artifact_path(REFERENCE_TREE; honor_overrides=false)
    root = get(ENV, "PD_GOLDEN_ROOT", default_root)
    return abspath(get(ENV, variable, joinpath(root, subdir)))
end

"""Offer missing reference data before tests. Unattended runs never read stdin.
`PD_GOLDEN_DOWNLOAD=ask|yes|no` controls consent; an explicit yes is required to download.
Explicit dataset/root paths are never populated or replaced by this installer.
"""
function prepare_golden_fixtures(; input::IO=stdin, output::IO=stdout,
        can_prompt::Bool=(input isa Base.TTY &&
            lowercase(get(ENV, "CI", "false")) ∉ ("true", "1")))
    mode = lowercase(get(ENV, "PD_GOLDEN_DOWNLOAD", "ask"))
    mode in ("ask", "yes", "no") || error("PD_GOLDEN_DOWNLOAD must be ask, yes, or no")
    missing = [kind for kind in keys(DATASETS) if !isdir(golden_directory(kind))]
    isempty(missing) && return nothing
    downloadable = filter(missing) do kind
        variable, subdir = getproperty(DATASETS, kind)
        !haskey(ENV, "PD_GOLDEN_ROOT") && !haskey(ENV, variable) &&
            !ispath(joinpath(@__DIR__, "golden", subdir))
    end
    if isempty(downloadable)
        println(output, "Missing explicitly configured reference paths must be supplied manually.")
        return nothing
    end
    if mode == "no" || (mode == "ask" && !can_prompt)
        println(output, "Reference download skipped. Set PD_GOLDEN_DOWNLOAD=yes to allow it in unattended runs.")
        return nothing
    end
    url = get(ENV, "PD_GOLDEN_URL", REFERENCE_URL)
    if isempty(url)
        message = "Reference archive URL is not configured. Set PD_GOLDEN_URL to the published archive or use PD_GOLDEN_ROOT."
        mode == "yes" && error(message)
        println(output, message, " Download skipped.")
        return nothing
    end
    if mode == "ask"
        println(output, "Download the 24.8 MB historical references for the full test suite?")
        println(output, "Source: ", url)
        print(output, "Allow download? [y/N] ")
        flush(output)
        answer = lowercase(strip(readline(input)))
        if answer ∉ ("y", "yes")
            println(output, "Reference download skipped; missing comparisons will be skipped (strict mode stops).")
            return nothing
        end
    end
    println(output, "Downloading and verifying historical references (24.8 MB)...")
    flush(output)
    result = download_artifact(REFERENCE_TREE, url, REFERENCE_SHA256; io=output)
    result === true || error("Reference download failed: $(sprint(showerror, result))")
    verify_artifact(REFERENCE_TREE; honor_overrides=false) || error("Reference archive tree hash mismatch")
    root = artifact_path(REFERENCE_TREE; honor_overrides=false)
    for (_, subdir) in values(DATASETS)
        verify_dataset(joinpath(root, subdir))
    end
    println(output, "Verified references cached at ", root)
    return nothing
end

"""Verify an available dataset once per process; incomplete or damaged data is an error."""
function verify_dataset(dir)
    dir in VERIFIED && return
    manifest = joinpath(dir, "SHA256SUMS")
    isfile(manifest) || error("Golden dataset $dir has no SHA256SUMS; supply a complete dataset")
    records = 0
    for line in eachline(manifest)
        isempty(strip(line)) && continue
        parts = split(strip(line); limit=2)
        length(parts) == 2 || error("Malformed golden checksum entry in $manifest")
        checksum, rawname = parts
        name = lstrip(strip(rawname), '*')
        occursin(r"^[0-9a-fA-F]{64}$", checksum) || error("Invalid checksum in $manifest")
        # Fixture records are flat files; reject paths outside the dataset.
        basename(name) == name && name != "." && name != ".." || error("Invalid fixture name in $manifest")
        file = joinpath(dir, name)
        isfile(file) || error("Golden record $file is missing from an existing dataset")
        bytes2hex(sha256(read(file))) == lowercase(checksum) || error("Golden record $file changed (hash mismatch)")
        records += 1
    end
    records > 0 || error("Golden dataset $dir has an empty SHA256SUMS")
    push!(VERIFIED, dir)
    return nothing
end

function golden_available(kind::Symbol; warn::Bool=true)
    dir = golden_directory(kind)
    if isdir(dir)
        verify_dataset(dir)
        return true
    end
    ispath(dir) && error("Golden dataset path $dir is not a directory")
    get(ENV, "PD_REQUIRE_GOLDEN", "0") == "1" &&
        error("Required golden dataset $kind is absent at $dir; set PD_GOLDEN_ROOT or $(getproperty(DATASETS, kind)[1])")
    if warn && !(dir in WARNED)
        @warn "Golden dataset unavailable; its comparison testsets will be skipped (Broken), not validated" dataset=kind directory=dir variable=getproperty(DATASETS, kind)[1]
        push!(WARNED, dir)
    end
    return false
end

"""Announce missing datasets before the suite; strict mode requires all four."""
function check_golden_fixtures()
    missing = [kind for kind in keys(DATASETS) if !golden_available(kind; warn=false)]
    if !isempty(missing)
        @warn "External golden fixtures are absent: this run is partial validation. Set PD_GOLDEN_ROOT (or per-dataset overrides); PD_REQUIRE_GOLDEN=1 requires full validation." datasets=missing
        union!(WARNED, golden_directory.(missing))
    end
    return missing
end

"""Run a normal Test.@testset when its dataset exists; otherwise record a visible skip.
For-loop testsets check availability inside each iteration, so `kind` may use its loop variables."""
macro golden_testset(kind, args...)
    isempty(args) && error("@golden_testset requires a testset body")
    body = deepcopy(args[end])
    body isa Expr && body.head in (:block, :for) || error("@golden_testset expects begin/end or a for loop")
    available = GlobalRef(@__MODULE__, :golden_available)
    skip = Expr(:macrocall, GlobalRef(Test, Symbol("@test_skip")), __source__, false)
    guard(b) = quote
        if $available($kind)
            $b
        else
            $skip
        end
    end
    if body.head == :for
        body.args[end] = guard(body.args[end])
    else
        body = guard(body)
    end
    return esc(Expr(:macrocall, GlobalRef(Test, Symbol("@testset")), __source__, args[1:end-1]..., body))
end
end
